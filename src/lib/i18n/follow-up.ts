export const FOLLOW_UP_CATALOGS: Record<Locale, Catalog> = { en, hi, ta, te, kn };

/** The line for `key` in `locale`, with each `{name}` replaced from `vars`. */
export function ft(locale: Locale, key: FollowUpKey, vars: Record<string, string | number> = {}): string {
  return FOLLOW_UP_CATALOGS[locale][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
