export const PORTAL_CATALOGS: Record<Locale, Catalog> = { en, hi, ta, te, kn, mr, bn, ml, gu };

/** A portal line in `locale`, with {placeholders} filled; unknown ones stay as written. */
export function pt(locale: Locale, key: PortalKey, vars: Record<string, string | number> = {}): string {
  const line = PORTAL_CATALOGS[locale][key] ?? en[key];
  return line.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
